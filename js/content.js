export function fallbackPeople(rng, n) {
  const faces = rng.sample(FACES, n);
  return faces.map(face => {
    const female = /👩|👵|🧕|♀️/.test(face);
    return {
      face,
      name: rng.pick(female ? NAMES_F : NAMES_M),
      profession: rng.pick(PROFESSIONS),
      city: rng.pick(CITIES),
      hobby: rng.pick(HOBBIES),
    };
  });
}

export function fallbackShopping(rng, n) {
  return { context: rng.pick(SHOPPING_CONTEXTS), items: rng.sample(GROCERIES, n) };
}

export function fallbackStory(rng) {
  // Simple template story with concrete recallable facts. Phrased to avoid Ukrainian declension issues.
  const p = fallbackPeople(rng, 2);
  const place = rng.pick(PLACES);
  const hour = rng.int(8, 19);
  const day = rng.pick(['понеділок','вівторок','середу','четвер','п\'ятницю','суботу']);
  const item = rng.pick(GROCERIES);
  const num = rng.int(12, 97);
  const COLORS = ['синій','червоний','зелений','жовтий','чорний','білий'];
  const color = rng.pick(COLORS);
  const floor = rng.int(2, 9);
  const text = `У ${day} о ${hour}:00 біля місця «${place}» ви зустріли людину на ім'я ${p[0].name}. Професія цієї людини — ${p[0].profession}, а хобі — ${p[0].hobby}. Поруч була ще одна людина, ${p[1].name}, родом з міста ${p[1].city}, у куртці кольору «${color}». Вони попросили вас купити ${item} і занести на ${floor} поверх, квартира ${num}.`;
  const qs = [
    { q: 'Як звали першу людину?', a: p[0].name, opts: [p[0].name, p[1].name, rng.pick(NAMES_M), rng.pick(NAMES_F)] },
    { q: 'О котрій годині це сталося?', a: `${hour}:00`, opts: [`${hour}:00`, `${hour + 1}:00`, `${hour - 1}:00`, `${hour + 2}:00`] },
    { q: 'Де відбулась зустріч?', a: place, opts: [place, ...rng.sample(PLACES.filter(x => x !== place), 3)] },
    { q: `Яка професія у ${p[0].name}?`, a: p[0].profession, opts: [p[0].profession, ...rng.sample(PROFESSIONS.filter(x => x !== p[0].profession), 3)] },
    { q: `З якого міста ${p[1].name}?`, a: p[1].city, opts: [p[1].city, ...rng.sample(CITIES.filter(x => x !== p[1].city), 3)] },
    { q: 'Якого кольору була куртка?', a: color, opts: [color, ...rng.sample(COLORS.filter(c => c !== color), 3)] },
    { q: 'Що просили купити?', a: item, opts: [item, ...rng.sample(GROCERIES.filter(x => x !== item), 3)] },
    { q: 'Який номер квартири?', a: String(num), opts: [String(num), String(num + 3), String(num - 7), String(num + 11)] },
    { q: 'На який поверх треба занести?', a: String(floor), opts: [String(floor), String(floor + 1), String(floor - 1), String(floor + 3)] },
  ];
  return { title: 'Зустріч на вулиці', text, questions: rng.shuffle(qs).slice(0, 5).map(x => ({ ...x, opts: rng.shuffle(x.opts) })) };
}
